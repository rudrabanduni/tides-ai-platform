"""live_instance.py - Separate LIVE (paid Claude) instance of TIDES-AI.

Live data never mixes with the demo or the protected historical databases:
  * database  : tides_live.db
  * uploads   : uploads_live/
  * settings  : .env.live (JWT secret + login password only; the Anthropic key is NEVER stored)

The Anthropic API key is supplied at start-up through a hidden prompt (scripts/start_live.ps1) and
exists only in the environment of the running processes.

Usage:
    .venv\\Scripts\\python.exe scripts\\live_instance.py [--show-credentials]
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

LIVE_DB = PROJECT_ROOT / "tides_live.db"
LIVE_UPLOADS = PROJECT_ROOT / "uploads_live"
LIVE_ENV_FILE = PROJECT_ROOT / ".env.live"
LIVE_EMAIL = "evaluator@tides.ai"
PROTECTED = {"tides_ai.db", "tides_dev.db", "tides_demo.db"}

# Decided by the user on 2026-11-22: $0.60 per evaluation, Sonnet 5.5 for the six specialists.
LIVE_BUDGET_USD = "0.60"
LIVE_REASONING_MODEL = "claude-sonnet-5-5"
LIVE_FAST_MODEL = "claude-haiku-5-5"


def load_live_env() -> dict[str, str]:
    values: dict[str, str] = {}
    if LIVE_ENV_FILE.exists():
        for line in LIVE_ENV_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.strip().startswith("#"):
                k, _, v = line.partition("=")
                values[k.strip()] = v.strip()
    return values


def ensure_live_env() -> dict[str, str]:
    values = load_live_env()
    changed = False
    if not values.get("TIDES_LIVE_PASSWORD"):
        values["TIDES_LIVE_PASSWORD"] = f"Tides-Live-{secrets.token_urlsafe(9)}"
        changed = True
    if not values.get("JWT_SECRET_KEY"):
        values["JWT_SECRET_KEY"] = secrets.token_urlsafe(48)
        changed = True
    values.setdefault("TIDES_LIVE_EMAIL", LIVE_EMAIL)
    # Never persist provider keys in this file.
    values.pop("ANTHROPIC_API_KEY", None)
    if changed or not LIVE_ENV_FILE.exists():
        LIVE_ENV_FILE.write_text(
            "# TIDES-AI LIVE instance - generated by scripts/live_instance.py. Gitignored.\n"
            "# The Anthropic API key is never stored here.\n"
            + "".join(f"{k}={v}\n" for k, v in values.items()),
            encoding="utf-8",
        )
    return values


def live_environment(values: dict[str, str]) -> dict[str, str]:
    """Environment for live processes. ANTHROPIC_API_KEY is inherited from the launcher only."""
    return {
        "APP_ENV": "development",
        "DATABASE_URL": f"sqlite:///{LIVE_DB.as_posix()}",
        "UPLOAD_DIR": str(LIVE_UPLOADS),
        "TIDES_LIVE_EVAL_REPORT_PATH": str(LIVE_UPLOADS / "telemetry" / "live_eval_run_report.json"),
        "AI_PROVIDER": "anthropic",
        "AI_ENABLED": "true",
        "LITELLM_MODEL": LIVE_REASONING_MODEL,
        "AI_REASONING_MODEL": LIVE_REASONING_MODEL,
        "AI_FAST_MODEL": LIVE_FAST_MODEL,
        "AI_MAX_EVALUATION_BUDGET_USD": LIVE_BUDGET_USD,
        "AI_MAX_EVALUATION_BUDGET": LIVE_BUDGET_USD,
        "AI_MAX_RETRIES": "1",
        "AI_DOMAIN_BATCH_MAX_CRITERIA": "3",
        "AI_DOMAIN_BATCH_MAX_RETRIES": "0",
        "AI_DOMAIN_SPLIT_ON_TRUNCATION": "true",
        "AI_STRUCTURED_THINKING_MODE": os.environ.get("AI_STRUCTURED_THINKING_MODE", "off"),
        "TAVILY_API_KEY": "",
        "RESEARCH_API_KEY": "",
        "RESEARCH_PROVIDER": "disabled",
        "ALLOW_UI_LIVE_EVALUATIONS": "true",
        "EVALUATION_RUNNER_MODE": "thread",
        "DEV_MODE": "false",
        "JWT_SECRET_KEY": values["JWT_SECRET_KEY"],
        "CORS_ORIGINS": "http://localhost:3000,http://127.0.0.1:3000",
    }


def init_live_database() -> Path:
    values = ensure_live_env()
    if LIVE_DB.name.lower() in PROTECTED:
        raise RuntimeError("Refusing to initialise a protected database")
    (LIVE_UPLOADS / "graphs").mkdir(parents=True, exist_ok=True)
    (LIVE_UPLOADS / "telemetry").mkdir(parents=True, exist_ok=True)
    env = live_environment(values)
    for k, v in env.items():
        os.environ[k] = v
    from app.core.config import get_settings

    get_settings.cache_clear()
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    from app.db.base import Base

    engine = create_engine(env["DATABASE_URL"], connect_args={"check_same_thread": False})
    Base.metadata.create_all(bind=engine)
    with sessionmaker(bind=engine)() as db:
        from app.modules.users.service import UserService

        svc = UserService(db)
        svc.ensure_default_roles()
        if not svc.users.get_by_email(values["TIDES_LIVE_EMAIL"]):
            svc.bootstrap_admin(name="TIDES Evaluator", email=values["TIDES_LIVE_EMAIL"], password=values["TIDES_LIVE_PASSWORD"])
    engine.dispose()
    return LIVE_DB


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--show-credentials", action="store_true")
    args = ap.parse_args()
    path = init_live_database()
    vals = load_live_env()
    print(f"Live database ready: {path}")
    print(f"Live login email:    {vals.get('TIDES_LIVE_EMAIL')}")
    if args.show_credentials:
        print(f"Live password:       {vals.get('TIDES_LIVE_PASSWORD')}")
    else:
        print(f"Live password:       stored in {LIVE_ENV_FILE.name} (run with --show-credentials to print)")
