"""init_demo_db.py - Clean, repeatable offline demonstration database.

Creates (or resets) the dedicated demonstration database `tides_demo.db` and its upload
directory `uploads_demo/`, then seeds the default roles and one local demo analyst account.

Safety:
  * refuses to touch tides_ai.db (protected snapshot) or tides_dev.db (historical PETREVOLT data)
  * --reset deletes ONLY tides_demo.db(-journal/-wal/-shm) and uploads_demo/
  * the demo password is generated once and stored in the gitignored file `.env.demo`
    (never printed by default, never committed)

Usage:
    .venv\\Scripts\\python.exe scripts\\init_demo_db.py            # create if missing
    .venv\\Scripts\\python.exe scripts\\init_demo_db.py --reset    # wipe demo data and recreate
    .venv\\Scripts\\python.exe scripts\\init_demo_db.py --show-credentials
"""

from __future__ import annotations

import argparse
import os
import secrets
import shutil
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

DEMO_DB = PROJECT_ROOT / "tides_demo.db"
DEMO_UPLOADS = PROJECT_ROOT / "uploads_demo"
DEMO_ENV_FILE = PROJECT_ROOT / ".env.demo"
DEMO_EMAIL = "analyst@tides.ai"
PROTECTED = {"tides_ai.db", "tides_dev.db"}


def load_demo_env() -> dict[str, str]:
    values: dict[str, str] = {}
    if DEMO_ENV_FILE.exists():
        for line in DEMO_ENV_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.strip().startswith("#"):
                k, _, v = line.partition("=")
                values[k.strip()] = v.strip()
    return values


def ensure_demo_env() -> dict[str, str]:
    """Creates .env.demo with a random JWT secret and demo password on first use."""
    values = load_demo_env()
    changed = False
    if not values.get("TIDES_DEMO_PASSWORD"):
        values["TIDES_DEMO_PASSWORD"] = f"Tides-Demo-{secrets.token_urlsafe(9)}"
        changed = True
    if not values.get("JWT_SECRET_KEY"):
        values["JWT_SECRET_KEY"] = secrets.token_urlsafe(48)
        changed = True
    values.setdefault("TIDES_DEMO_EMAIL", DEMO_EMAIL)
    if changed or not DEMO_ENV_FILE.exists():
        DEMO_ENV_FILE.write_text(
            "# LOCAL OFFLINE DEMONSTRATION ONLY - generated by scripts/init_demo_db.py. Gitignored.\n"
            + "".join(f"{k}={v}\n" for k, v in values.items()),
            encoding="utf-8",
        )
    return values


def demo_environment(values: dict[str, str]) -> dict[str, str]:
    """Environment for every demo process: isolated DB/uploads, mock provider, no keys."""
    return {
        "APP_ENV": "development",
        "DATABASE_URL": f"sqlite:///{DEMO_DB.as_posix()}",
        "UPLOAD_DIR": str(DEMO_UPLOADS),
        "TIDES_LIVE_EVAL_REPORT_PATH": str(DEMO_UPLOADS / "telemetry" / "demo_eval_run_report.json"),
        "AI_PROVIDER": "mock",
        "AI_ENABLED": "false",
        "ANTHROPIC_API_KEY": "",
        "TAVILY_API_KEY": "",
        "RESEARCH_API_KEY": "",
        "RESEARCH_PROVIDER": "disabled",
        "ALLOW_UI_LIVE_EVALUATIONS": "false",
        "EVALUATION_RUNNER_MODE": "thread",
        "DEV_MODE": "false",
        "JWT_SECRET_KEY": values["JWT_SECRET_KEY"],
        "CORS_ORIGINS": "http://localhost:3000,http://127.0.0.1:3000",
    }


def _assert_safe(path: Path) -> None:
    if path.name.lower() in PROTECTED or path.resolve() != DEMO_DB.resolve():
        raise RuntimeError(f"Refusing to operate on {path} (only {DEMO_DB.name} is allowed).")


def init_demo_database(reset: bool = False) -> Path:
    values = ensure_demo_env()
    _assert_safe(DEMO_DB)
    if reset:
        for suffix in ("", "-journal", "-wal", "-shm"):
            p = Path(str(DEMO_DB) + suffix)
            if p.exists():
                p.unlink()
        if DEMO_UPLOADS.exists() and DEMO_UPLOADS.resolve().parent == PROJECT_ROOT.resolve() and DEMO_UPLOADS.name == "uploads_demo":
            shutil.rmtree(DEMO_UPLOADS)
    (DEMO_UPLOADS / "graphs").mkdir(parents=True, exist_ok=True)
    (DEMO_UPLOADS / "telemetry").mkdir(parents=True, exist_ok=True)

    os.environ.update(demo_environment(values))
    from app.core.config import get_settings

    get_settings.cache_clear()
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    from app.db.base import Base

    engine = create_engine(os.environ["DATABASE_URL"], connect_args={"check_same_thread": False})
    Base.metadata.create_all(bind=engine)
    Session = sessionmaker(bind=engine)
    with Session() as db:
        from app.modules.users.service import UserService

        svc = UserService(db)
        svc.ensure_default_roles()
        if not svc.users.get_by_email(values["TIDES_DEMO_EMAIL"]):
            svc.bootstrap_admin(name="Demo Incubation Analyst", email=values["TIDES_DEMO_EMAIL"], password=values["TIDES_DEMO_PASSWORD"])
    engine.dispose()
    return DEMO_DB


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Initialise the TIDES-AI offline demonstration database")
    ap.add_argument("--reset", action="store_true", help="Delete tides_demo.db and uploads_demo/ first")
    ap.add_argument("--show-credentials", action="store_true", help="Print the local demo login")
    args = ap.parse_args()
    path = init_demo_database(reset=args.reset)
    vals = load_demo_env()
    print(f"Demo database ready: {path}")
    print(f"Demo uploads:        {DEMO_UPLOADS}")
    print(f"Demo login email:    {vals.get('TIDES_DEMO_EMAIL')}")
    if args.show_credentials:
        print(f"Demo password:       {vals.get('TIDES_DEMO_PASSWORD')}  (local demo only)")
    else:
        print(f"Demo password:       stored in {DEMO_ENV_FILE.name} (run with --show-credentials to print)")
